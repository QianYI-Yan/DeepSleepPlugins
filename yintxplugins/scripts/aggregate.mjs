/**
 * 合集生成器：`aggregate.json`（唯一事实来源）→ 两个生成物
 *
 *   1. `cordis.patch.yml` —— 官方 loader 应用的补丁层：合集主行 + 每个子插件一行
 *   2. `lib/rows.json`    —— 机器可读的行目录（父 host 半的 /yintx/status 与降级展示用）
 *
 * 为什么清单用 JSON 而不是 dshall 的 YAML：本脚本要**零依赖**（不引 yaml 包），
 * 保证离线 / 干净环境里也能重新生成。生成物仍是 loader 要的 YAML。
 *
 * 用法：
 *   node scripts/aggregate.mjs           # 生成
 *   node scripts/aggregate.mjs --check   # 只校验生成物与清单一致（测试用，退出码 1 = 不一致）
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const MANIFEST = join(ROOT, 'aggregate.json')
const PATCH = join(ROOT, 'cordis.patch.yml')
const ROWS = join(ROOT, 'lib', 'rows.json')

/** 单引号标量：YAML 里 @ 不能开裸标量；带 @ : # 或首尾空白的都加引号。 */
function scalar(value) {
  const text = String(value)
  const needsQuote = text === '' || /^[%@\u0060]|[:#]|^\s|\s$/.test(text)
  return needsQuote ? "'" + text.replaceAll("'", "''") + "'" : text
}

/** 校验清单：结构不对就报错，别生成半成品。 */
export function validate(manifest) {
  const problems = []
  if (!manifest || typeof manifest !== 'object') problems.push('清单不是对象')
  const ns = manifest && manifest.namespace
  if (typeof ns !== 'string' || !/^[a-z][a-z0-9-]*$/.test(ns)) problems.push('namespace 不合法：' + String(ns))
  if (!manifest || !manifest.self || typeof manifest.self.id !== 'string') problems.push('缺少 self.id')
  const plugins = manifest && manifest.plugins
  if (!Array.isArray(plugins) || plugins.length === 0) problems.push('plugins 必须是非空数组')
  const seen = new Set()
  const list = Array.isArray(plugins) ? plugins : []
  for (let index = 0; index < list.length; index += 1) {
    const item = list[index] || {}
    const where = 'plugins[' + index + ']'
    const keys = ['subpath', 'plugin', 'fallback', 'title', 'summary']
    for (const key of keys) {
      if (typeof item[key] !== 'string' || item[key].trim() === '') problems.push(where + '.' + key + ' 缺失')
    }
    if (typeof item.subpath === 'string' && !/^[a-z0-9-]+$/.test(item.subpath)) {
      problems.push(where + '.subpath 只能 kebab-case：' + item.subpath)
    }
    if (seen.has(item.subpath)) problems.push(where + '.subpath 重复：' + String(item.subpath))
    seen.add(item.subpath)
    if (item.client === true) {
      // 客户端半的行**必须**给出子插件客户端 bundle 的路径：合集宿主半要把它送出去，
      // 子插件的包名在 link:/file: 安装下解析不到，只能靠这条同仓相对路径。
      if (typeof item.clientEntry !== 'string' || item.clientEntry.trim() === '') {
        problems.push(where + '.clientEntry 缺失（client: true 的行要指向子插件的客户端 bundle）')
      } else if (!item.clientEntry.startsWith('./') && !item.clientEntry.startsWith('../')) {
        problems.push(where + '.clientEntry 应以 ./ 或 ../ 开头（相对合集包根目录）：' + item.clientEntry)
      }
    } else if (item.clientEntry !== undefined) {
      problems.push(where + '.clientEntry 只在 client: true 的行上有意义')
    }
  }
  return problems
}

/**
 * 校验每个客户端 bundle 真的能当 bundle 用，且注册 id 就是子插件包名。
 * 客户端半是 `require('<包名>')` 把子插件拿回来的，两边**必须**同源，否则静默挂不上。
 * @returns 问题描述数组（空数组 = 通过）。
 */
export function checkClientEntries(manifest) {
  const problems = []
  for (const item of manifest.plugins) {
    if (item.client !== true) continue
    const relative = item.clientEntry
    let text
    try {
      text = readFileSync(join(ROOT, relative), 'utf8')
    } catch (error) {
      problems.push(relative + ' 读不到：' + (error?.code ?? error?.message ?? error))
      continue
    }
    if (!/window\s*\.\s*__ModuleLoader__\s*\.\s*load\s*\(/.test(text)) {
      problems.push(relative + ' 不像客户端 bundle（没看到 window.__ModuleLoader__.load 注册）')
    }
    const id = new RegExp("id:\\s*['\"]" + item.plugin.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + "['\"]")
    if (!id.test(text)) {
      problems.push(relative + ' 的注册 id 不是 ' + item.plugin + '（客户端半按包名 require 它）')
    }
  }
  return problems
}

/** cordis.patch.yml 文本。 */
export function renderPatch(manifest) {
  const ns = manifest.namespace
  const out = []
  const push = (line) => out.push(line)

  push('# AUTO-GENERATED by scripts/aggregate.mjs — 不要手改')
  push('# 本文件由 aggregate.json 生成；改清单后重跑：node scripts/aggregate.mjs')
  push('#')
  push('# 行 id 统一带 yintx- 命名空间，避免和三个子插件的独立安装行撞 id：')
  push('#   独立安装 dsh-plugin-open-folder → 行 id 就是 dsh-plugin-open-folder')
  push('#   走本合集                      → 行 id 是 ' + ns + '-open-folder')
  push('#')
  push('# 每行的 name 指向本包的子路径导出（= lib/shells/shell.js，通用外壳），')
  push('# config.fallback 是包内真实实现的相对路径（相对包根）；外壳动态 import 它，失败只记降级、不回滚整组。')
  push('# 官方插件列表会把 name 里的子路径显示成独立一行（yintxplugins/<子路径>），')
  push('# 所以在「设置 → 插件」里可以逐个子插件开关。')
  push('')
  push('# ── 合集主行（父 host 半：账本 / 健康路由 / 中文概览） ──')
  push('- insert:')
  push('    - id: ' + manifest.self.id)
  push("      name: 'yintxplugins'")

  for (const item of manifest.plugins) {
    push('')
    push('# ── ' + item.title + '（' + item.plugin + '）' + (item.client === true ? '' : ' · 纯宿主侧') + ' ──')
    push('- insert:')
    push('    - id: ' + ns + '-' + item.subpath)
    push("      name: 'yintxplugins/" + item.subpath + "'")
    push('      config:')
    push('        # 行 id 回传给外壳：外壳靠 config.id 记账（缺了它账本会记成 (no-row)，/yintx/status 就判错行）')
    push('        id: ' + scalar(ns + '-' + item.subpath))
    push('        # 只写包内实现路径：合集自包含，不再按包名解析（那三个子插件包不再单独安装）')
    push('        fallback: ' + scalar(item.fallback))
  }
  return out.join('\n') + '\n'
}

/** lib/rows.json 文本（父半与测试读它；与清单同源）。 */
export function renderRows(manifest) {
  const rows = [
    {
      id: manifest.self.id,
      name: 'yintxplugins',
      kind: 'self',
      title: manifest.title,
      summary: manifest.summary,
      plugin: null,
      client: true,
    },
  ]
  for (const item of manifest.plugins) {
    rows.push({
      id: manifest.namespace + '-' + item.subpath,
      name: 'yintxplugins/' + item.subpath,
      kind: 'sub',
      subpath: item.subpath,
      title: item.title,
      summary: item.summary,
      plugin: item.plugin,
      fallback: item.fallback,
      client: item.client === true,
      ...(item.client === true ? { clientEntry: item.clientEntry } : {}),
    })
  }
  const payload = {
    namespace: manifest.namespace,
    title: manifest.title,
    summary: manifest.summary,
    rows,
  }
  return JSON.stringify(payload, null, 2) + '\n'
}

export function build() {
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
  const problems = validate(manifest)
  if (problems.length > 0) throw new Error('aggregate.json 不合法：\n  - ' + problems.join('\n  - '))
  const clientProblems = checkClientEntries(manifest)
  if (clientProblems.length > 0) throw new Error('子插件客户端 bundle 有问题：\n  - ' + clientProblems.join('\n  - '))
  return { manifest, patch: renderPatch(manifest), rows: renderRows(manifest) }
}

/**
 * CLI 入口判定：**被 import 时绝不落盘**（测试会 import 本模块拿内存里的生成结果）。
 */
const invokedDirectly =
  process.argv[1] !== undefined && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))

if (invokedDirectly) {
  const check = process.argv.includes('--check')
  const { patch, rows } = build()

  if (check) {
    const problems = []
    if (!existsSync(PATCH) || readFileSync(PATCH, 'utf8') !== patch) problems.push('cordis.patch.yml 与清单不一致')
    if (!existsSync(ROWS) || readFileSync(ROWS, 'utf8') !== rows) problems.push('lib/rows.json 与清单不一致')
    if (problems.length > 0) {
      console.error('✗ ' + problems.join('；') + '\n  跑 node scripts/aggregate.mjs 重新生成')
      process.exit(1)
    }
    console.log('✓ 生成物与 aggregate.json 一致')
    process.exit(0)
  }

  mkdirSync(join(ROOT, 'lib'), { recursive: true })
  writeFileSync(PATCH, patch, 'utf8')
  writeFileSync(ROWS, rows, 'utf8')
  console.log('✓ 已生成 cordis.patch.yml 与 lib/rows.json')
}
